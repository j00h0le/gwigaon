#!/usr/bin/env bash
# Publishes the trusted-contact page (web/contact) to its public GitHub Pages repo (T20).
# Only the page itself leaves this repo: index.html, app.js, state.js, style.css and a generated
# config.js pointing at the remote Supabase project with its publishable key (public by design).
#
# Usage: scripts/publish-contact.sh
#   CONTACT_REPO, CONTACT_SUPABASE_URL, CONTACT_SUPABASE_KEY override the defaults below.
set -euo pipefail

REPO="${CONTACT_REPO:-j00h0le/gwigaon-contact}"
URL="${CONTACT_SUPABASE_URL:-https://femehqwacxcoeevbzvtd.supabase.co}"
KEY="${CONTACT_SUPABASE_KEY:-sb_publishable_m6UDE6--FQ-313yVZH_5jA_PZnPYJdv}"
SRC="$(cd "$(dirname "$0")/../web/contact" && pwd)"
FILES=(index.html app.js state.js style.css)

case "$KEY" in
  sb_publishable_*) ;;
  *) echo "refusing: CONTACT_SUPABASE_KEY must be a publishable key (sb_publishable_...)" >&2; exit 1 ;;
esac

if ! gh repo view "$REPO" >/dev/null 2>&1; then
  gh repo create "$REPO" --public --description "귀가온 trusted-contact page (static, GitHub Pages)"
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
if ! git clone -q "https://github.com/$REPO.git" "$WORK/site" 2>/dev/null; then
  mkdir -p "$WORK/site" && git -C "$WORK/site" init -q -b main
  git -C "$WORK/site" remote add origin "https://github.com/$REPO.git"
fi
SITE="$WORK/site"

for f in "${FILES[@]}"; do cp "$SRC/$f" "$SITE/$f"; done
cat > "$SITE/config.js" <<EOF
// Generated by scripts/publish-contact.sh: the remote project's URL and publishable key (public by design).
window.GWIGAON_CONFIG = {
  supabaseUrl: "$URL",
  supabaseKey: "$KEY",
};
EOF
touch "$SITE/.nojekyll"

git -C "$SITE" add -A
if git -C "$SITE" diff --cached --quiet; then
  echo "contact page: no changes"
else
  git -C "$SITE" commit -q -m "Publish contact page from $(git -C "$SRC" rev-parse --short HEAD)"
  git -C "$SITE" push -q origin HEAD:main
  echo "contact page: pushed"
fi

if ! gh api "repos/$REPO/pages" >/dev/null 2>&1; then
  gh api -X POST "repos/$REPO/pages" -f "source[branch]=main" -f "source[path]=/" >/dev/null
  echo "pages: enabled"
fi
echo "https://${REPO%%/*}.github.io/${REPO#*/}/"
